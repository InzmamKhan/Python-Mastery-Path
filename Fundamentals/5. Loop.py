# While Loop
# These are used to perform any other function rather than Doing stuff on List, Tuple or any other Ranged Stuff

# Syntax
a=0
while(a!=10):
    print(a)
    a+=1

# For Loop
# These are used to perform of Ranged Iterations 
for i in range (0, 50, 2):
    print(i)

a = ["Hello", 250, True]
for i in (a):
    print(i)