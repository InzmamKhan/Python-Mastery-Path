# To Find The NEAREST WHOLE INTEGER
result_1 = round(3.14)
print(result_1)



# To Find The ABSOLUTE VALUE of a Number
result_2 = abs(-5)
print(result_2)



# To Find The EXPONENTIAL POWER
result_3 = pow(10, 4)
print(result_3)



# To Find The MAXIMUM & MINIMUM Value Among Given Numbers
result_4 = max(10,100)
result_5 = min(10,100)
print(result_4)
print(result_5)
